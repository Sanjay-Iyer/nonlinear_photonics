def paper_benchmark_case(cfg: Mapping[str, Any]) -> StructureCase:
    """The paper's ideal-abrupt ACQW, transcribed and then checked."""

    paper = cfg["paper_benchmark"]
    case = StructureCase(
        case_id="paper_benchmark",
        label="Paper benchmark (ideal abrupt)",
        group=GROUP_PAPER,
        thick_well_nm=float(paper["thick_well_nm"]),
        thin_well_nm=float(paper["thin_well_nm"]),
        tunnel_barrier_nm=float(paper["tunnel_barrier_nm"]),
        left_grade_nm=0.0,
        right_grade_nm=0.0,
        grading_definition=cfg["grading"]["definition"],
        abrupt_threshold_nm=float(cfg["sweep"].get("abrupt_threshold_nm", 0.005)),
        period_barrier_nm=float(paper["period_barrier_nm"]),
        notes=(
            "ideal abrupt interfaces; the structure whose chi2 the paper states "
            "as 2340 pm/V at 1550 nm"
        ),
    )
    # Transcription is checked rather than trusted: these three numbers are the
    # only thing tying this demo to the paper's stated target.
    if abs(case.total_well_nm - float(paper["total_well_nm"])) > 1e-9:
        raise Cases16GError(
            f"paper benchmark total well is {case.total_well_nm} nm, config says "
            f"{paper['total_well_nm']} nm"
        )
    if abs(case.asymmetry_s - float(paper["asymmetry_s"])) > 5e-3:
        raise Cases16GError(
            f"paper benchmark asymmetry is {case.asymmetry_s:.4f}, config says "
            f"{paper['asymmetry_s']}"
        )
    period = case.total_well_nm + case.tunnel_barrier_nm + float(
        paper["period_barrier_nm"]
    )
    if abs(period - float(paper["total_period_nm"])) > 1e-9:
        raise Cases16GError(
            f"paper benchmark period sums to {period} nm, config says "
            f"{paper['total_period_nm']} nm"
        )
    if not case.is_fully_abrupt:
        raise Cases16GError("the paper benchmark must have abrupt interfaces.")
    return case


def all_cases(
    cfg: Mapping[str, Any], repository_root: Path,
    nnp_overrides: Sequence[str] | None = None,
) -> dict[str, Any]:
    """Every case in every group, plus the sweep design's provenance."""

    sweep, provenance = sweep_cases(cfg)
    return {
        GROUP_NNP: supplied_nnp_cases(cfg, repository_root, nnp_overrides),
        GROUP_SWEEP: sweep,
        GROUP_PAPER: [paper_benchmark_case(cfg)],
        "sweep_design": provenance,
        "grading_convention": grading16g.convention_note(cfg["grading"]["definition"]),
    }
