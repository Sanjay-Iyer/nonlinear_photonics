# Case records
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class NnpCase:
    """One supplied ``.nnp`` file, preserved exactly as given."""

    case_id: str
    label: str
    source_path: Path
    group: str = GROUP_NNP

    def as_record(self) -> dict[str, Any]:
        return {
            "group": self.group,
            "case_id": self.case_id,
            "label": self.label,
            "source": str(self.source_path),
            "source_kind": "supplied_nnp_file",
            "structure_generated_by": "the supplied file itself; not regenerated",
        }


@dataclass(frozen=True)
class StructureCase:
    """One ACQW structure this demo builds, from the sweep or the benchmark."""

    case_id: str
    label: str
    group: str
    thick_well_nm: float
    thin_well_nm: float
    tunnel_barrier_nm: float
    left_grade_nm: float
    right_grade_nm: float
    grading_definition: str = grading16g.DEFAULT_DEFINITION
    abrupt_threshold_nm: float = 0.005
    period_barrier_nm: float | None = None
    notes: str = ""

    @property
    def total_well_nm(self) -> float:
        return self.thick_well_nm + self.thin_well_nm

    @property
    def asymmetry_s(self) -> float:
        """``(d1 - d2) / (d1 + d2)``, the paper's structural asymmetry."""

        total = self.total_well_nm
        if total <= 0:
            raise Cases16GError(f"{self.case_id}: total well thickness is not positive.")
        return (self.thick_well_nm - self.thin_well_nm) / total

    @property
    def left_grade(self) -> grading16g.GradeWidths:
        return grading16g.describe(
            self.left_grade_nm, definition=self.grading_definition,
            abrupt_threshold_nm=self.abrupt_threshold_nm,
        )

    @property
    def right_grade(self) -> grading16g.GradeWidths:
        return grading16g.describe(
            self.right_grade_nm, definition=self.grading_definition,
            abrupt_threshold_nm=self.abrupt_threshold_nm,
        )

    @property
    def is_fully_abrupt(self) -> bool:
        return self.left_grade.is_abrupt and self.right_grade.is_abrupt

    def as_record(self) -> dict[str, Any]:
        return {
            "group": self.group,
            "case_id": self.case_id,
            "label": self.label,
            "source": "generated by Demo 16G",
            "source_kind": "generated_structure",
            "thick_well_nm": self.thick_well_nm,
            "thin_well_nm": self.thin_well_nm,
            "barrier_nm": self.tunnel_barrier_nm,
            "total_well_nm": self.total_well_nm,
            "asymmetry_s": self.asymmetry_s,
            "period_barrier_nm": self.period_barrier_nm,
            "left_grade_nm": self.left_grade_nm,
            "right_grade_nm": self.right_grade_nm,
            "grading_definition": self.grading_definition,
            **self.left_grade.as_record("left"),
            **self.right_grade.as_record("right"),
            "fully_abrupt": self.is_fully_abrupt,
            "notes": self.notes,
        }


