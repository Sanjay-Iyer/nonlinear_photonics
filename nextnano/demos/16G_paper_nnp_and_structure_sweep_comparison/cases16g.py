def supplied_nnp_cases(
    cfg: Mapping[str, Any], repository_root: Path,
    overrides: Sequence[str] | None = None,
) -> list[NnpCase]:
    """The supplied files, resolved repository-relative and never edited.

    ``overrides`` replaces the configured paths positionally, so the two files
    can be pointed somewhere else from the CLI without touching the config or
    baking a machine-specific path into the code.
    """

    entries = list(cfg["supplied_nnp"])
    if overrides:
        if len(overrides) > len(entries):
            raise Cases16GError(
                f"{len(overrides)} --nnp-file overrides for {len(entries)} "
                "configured supplied files"
            )
        for index, override in enumerate(overrides):
            entries[index] = {**entries[index], "path": override}
    cases = []
    for entry in entries:
        raw = Path(entry["path"])
        path = raw if raw.is_absolute() else Path(repository_root) / raw
        cases.append(NnpCase(
            case_id=str(entry["id"]), label=str(entry["label"]),
            source_path=path,
        ))
    return cases


# ---------------------------------------------------------------------------
# Group 2 -- Latin hypercube
# ---------------------------------------------------------------------------


def _latin_hypercube(
    count: int, dimensions: int, rng: np.random.Generator
) -> np.ndarray:
    """One LHS design in the unit cube: one sample per stratum per dimension."""

    design = np.empty((count, dimensions), dtype=float)
    for column in range(dimensions):
        permutation = rng.permutation(count)
        jitter = rng.random(count)
        design[:, column] = (permutation + jitter) / count
    return design


def _minimum_pairwise_distance(design: np.ndarray) -> float:
    difference = design[:, None, :] - design[None, :, :]
    distance = np.sqrt((difference**2).sum(axis=-1))
    np.fill_diagonal(distance, np.inf)
    return float(distance.min())


def maximin_design(
    count: int, dimensions: int, *, seed: int, candidates: int = 64
) -> tuple[np.ndarray, dict[str, Any]]:
    """The best of ``candidates`` seeded LHS designs, by maximin distance.

    Plain LHS guarantees one sample per stratum per axis but can still stack
    points along a diagonal. Drawing several designs from the same seeded
    generator and keeping the one whose closest pair is furthest apart costs
    nothing and gives a genuinely space-filling set -- and it stays exactly
    reproducible, because the generator is seeded and the selection rule is
    deterministic.
    """

    rng = np.random.default_rng(int(seed))
    best: np.ndarray | None = None
    best_distance = -1.0
    distances = []
    for _ in range(int(candidates)):
        design = _latin_hypercube(int(count), int(dimensions), rng)
        distance = _minimum_pairwise_distance(design)
        distances.append(distance)
        if distance > best_distance:
            best, best_distance = design, distance
    assert best is not None
    return best, {
        "seed": int(seed),
        "candidates_evaluated": int(candidates),
        "selected_minimum_pairwise_distance": best_distance,
        "candidate_distance_mean": float(np.mean(distances)),
        "candidate_distance_worst": float(np.min(distances)),
        "selection_rule": "maximin over seeded Latin-hypercube candidates",
    }


def sweep_cases(cfg: Mapping[str, Any]) -> tuple[list[StructureCase], dict[str, Any]]:
    """The 20 deterministic structures, plus the design's provenance."""

    sweep = cfg["sweep"]
    ranges = sweep["ranges_nm"]
    count = int(sweep["count"])
    quantum = float(sweep.get("quantize_nm", 0.01))
    threshold = float(sweep.get("abrupt_threshold_nm", 0.005))
    design, provenance = maximin_design(
        count, len(SWEEP_DIMENSIONS), seed=int(sweep["seed"]),
        candidates=int(sweep.get("maximin_candidates", 64)),
    )

    values: dict[str, np.ndarray] = {}
    for index, name in enumerate(SWEEP_DIMENSIONS):
        low, high = (float(v) for v in ranges[name])
        if high < low:
            raise Cases16GError(f"sweep range {name} is inverted: {low}..{high}")
        scaled = low + design[:, index] * (high - low)
        # Quantised so a structure can be rebuilt from the printed table alone.
        values[name] = np.round(scaled / quantum) * quantum

    cases = []
    for row in range(count):
        case_id = f"sweep_{row + 1:02d}"
        cases.append(StructureCase(
            case_id=case_id,
            label=case_id.replace("_", " "),
            group=GROUP_SWEEP,
            thick_well_nm=float(values["thick_well"][row]),
            thin_well_nm=float(values["thin_well"][row]),
            tunnel_barrier_nm=float(values["tunnel_barrier"][row]),
            left_grade_nm=float(values["left_grade"][row]),
            right_grade_nm=float(values["right_grade"][row]),
            grading_definition=cfg["grading"]["definition"],
            abrupt_threshold_nm=threshold,
            period_barrier_nm=float(cfg["numerics"]["domain_padding_nm"]),
        ))

    provenance.update({
        "dimensions": list(SWEEP_DIMENSIONS),
        "ranges_nm": {k: list(v) for k, v in ranges.items()},
        "count": count,
        "quantize_nm": quantum,
        "abrupt_threshold_nm": threshold,
        "grading_definition": cfg["grading"]["definition"],
        "abrupt_cases": [c.case_id for c in cases if c.is_fully_abrupt],
        "note": (
            "regenerating with the same config and seed reproduces these twenty "
            "structures exactly; no result is read at any point"
        ),
    })
    return cases, provenance


