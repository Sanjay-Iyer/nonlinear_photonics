"""The three groups, defined once and deterministically.

Group 1  the two supplied ``.nnp`` files, used verbatim
Group 2  20 Latin-hypercube ACQW structures around the paper design
Group 3  the paper's ideal-abrupt benchmark

Nothing here reads a result. The sweep is generated from a fixed seed before
anything is solved, so the twenty structures are a property of the config file
rather than of the order the solver happened to finish in.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Mapping, Sequence

import numpy as np
import yaml

import grading16g

GROUP_NNP = "supplied_nnp"
GROUP_SWEEP = "structure_sweep"
GROUP_PAPER = "paper_benchmark"
GROUPS = (GROUP_NNP, GROUP_SWEEP, GROUP_PAPER)

#: The order the sweep's dimensions are sampled in. Fixed, because the seed only
#: reproduces a design if the columns mean the same thing every time.
SWEEP_DIMENSIONS = (
    "thick_well", "thin_well", "tunnel_barrier", "left_grade", "right_grade",
)


class Cases16GError(ValueError):
    """A case definition that is malformed rather than merely unusual."""


def load_config(path: Path | None = None) -> dict[str, Any]:
    path = Path(path) if path else Path(__file__).resolve().parent / "config16g.yaml"
    if not path.is_file():
        raise Cases16GError(f"no Demo 16G configuration at {path}")
    payload = yaml.safe_load(path.read_text(encoding="utf-8"))
    if payload.get("optics", {}).get("absolute_scale_factor") is not None:
        raise Cases16GError(
            "optics.absolute_scale_factor is set. Demo 16G computes every chi2 "
            "from the physics and must not carry a fitted multiplier; remove it."
        )
    payload["_config_path"] = str(path)
    return payload


