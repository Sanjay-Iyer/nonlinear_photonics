def input_parameters_guide() -> str:
    lines = _header("Demo 13 input parameters guide")
    lines += [
        "Everything you can change, what it does, and whether changing it makes "
        "an existing optimization checkpoint unusable.",
        "",
        "**Checkpoint invalidation.** Some settings define *what the search space "
        "is*. Changing one means the stored trials describe a different problem, "
        "so Demo 13 refuses to resume and tells you to start a new experiment "
        "directory. That refusal is a safety feature.",
        "",
        "**The geometry rule that surprises people.** The widest grade a design "
        "can build is `central barrier thickness - minimum_flat_region_nm`. With "
        "a 0.10 nm flat region and a 0.80 nm minimum resolvable grade, an "
        "**abrupt** design may use the full 0.85 nm barrier, but a **genuinely "
        "graded** design needs a barrier of at least **0.90 nm**. Between 0.85 and "
        "0.90 nm the graded branch is empty and such proposals are refused.",
        "", "---", "",
    ]
    for entry in catalog13.PARAMETER_NOTES:
        lines += [
            f"## `{entry['path']}`", "",
            f"**{entry['plain']}**", "",
            f"- **Type:** {entry['kind']}",
            f"- **Units:** {entry['units']}",
            f"- **Raising it:** {entry['increase']}",
            f"- **Lowering it:** {entry['decrease']}",
            f"- **Interacts with:** {entry['interacts']}",
            f"- **Invalidates an existing checkpoint:** "
            f"{'yes' if entry['invalidates_checkpoint'] else 'no'}",
            "",
        ]
    return "\n".join(lines) + "\n"


