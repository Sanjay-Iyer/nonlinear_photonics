"""Render the beginner guides in ``guides/`` from the catalogue, not by hand.

A hand-written guide is stale the moment a column is renamed, and prose does not
fail a test.  These are generated from :mod:`catalog13`, whose entries are in
turn checked against the code that produces the artifacts, so a figure that
gains or loses a column cannot quietly keep its old description.

Run ``python guides13.py`` to regenerate. The tests in
``test_demo13_guides.py`` fail if the files on disk differ from what this module
produces, so a stale guide is a test failure rather than a discovery.
"""

