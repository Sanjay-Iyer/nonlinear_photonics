def write_all(directory: Path | None = None) -> list[Path]:
    target = Path(directory) if directory else GUIDES_DIR
    target.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name, builder in GUIDE_FILES.items():
        path = target / name
        path.write_text(builder(), encoding="utf-8", newline="\n")
        written.append(path)
    return written


